package br.com.amis.model;

public class Amis {

    private String name;
    private String color;
    private String model;

    public Amis(String name) {
        this.name = name;
    }

    public String getName() {
        return name;
    }

    public String getColor() {
        return color;
    }

    public String getModel() {
        return model;
    }

}
